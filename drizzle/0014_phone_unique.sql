-- 휴대폰 번호는 근태기록과 직원을 잇는 유일한 연결 키입니다. 근태 자료에는
-- 사원번호가 없고 휴대폰 번호가 필수 항목이라, 번호가 겹치면 그 근태를 누구
-- 것으로 붙일지 판정할 수 없습니다.
--
-- 대조는 숫자만 남긴 형태로 합니다. 같은 사람의 번호가 010-1234-5678,
-- 01012345678, +82-10-1234-5678 로 제각각 들어와도 한 사람으로 봐야 합니다.
-- 그래서 컬럼 값이 아니라 정규화한 값에 유일성을 겁니다.
--
-- NOT NULL 은 걸지 않습니다. 필수 여부는 사원 등록·수정 화면에서 막습니다.
-- 명부에 번호가 중복 기재된 사람이 실제로 있어(여치호·림부 같은 번호),
-- 데이터베이스에서 막아 버리면 그 사람을 아예 등록하지 못하거나 가짜 번호를
-- 넣게 됩니다. 비어 있는 편이 낫습니다 — 비면 근태가 안 붙고, 안 붙으면
-- 눈에 띄어 고치게 됩니다.
CREATE UNIQUE INDEX IF NOT EXISTS "employees_phone_digits_unique"
  ON "employees" (regexp_replace("phone", '[^0-9]', '', 'g'))
  WHERE "phone" IS NOT NULL AND regexp_replace("phone", '[^0-9]', '', 'g') <> '';
